export function generate_24h_history(device_id, current_level, warning_thresh) {
  const readings = [];
  const now = Date.now();
  const base_level = Math.max((current_level || 50) * 0.3, 10.0);

  for (let i = 24; i >= 0; i--) {
    const t = new Date(now - i * 3600000);
    let lvl = base_level;
    let rain = 0.0;

    if (i >= 2 && i <= 6) {
      const factor = 1.0 - Math.abs(i - 4) * 0.2;
      lvl = base_level + ((current_level || 60) - base_level) * factor + (Math.random() * 4 - 2);
      rain = Math.round((Math.random() * 30 + 15) * factor * 10) / 10;
    } else {
      lvl = base_level + (Math.random() * 6 - 3);
      rain = 0.0;
    }

    readings.push({
      device_id,
      water_level_cm: Math.round(Math.max(lvl, 4.0) * 10) / 10,
      flow_rate_lps: Math.round(Math.max(lvl * 3.8, 12.0) * 10) / 10,
      rainfall_mm_hr: rain,
      recorded_at: t.toISOString(),
      raw_payload: { battery: 92.0, rssi: -68 },
    });
  }
  return readings;
}



